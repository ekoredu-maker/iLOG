def _objective(subject: str, topic: str) -> str:
    if subject in ("수학", "과학", "사회"):
        return f"{topic}의 핵심 개념과 관계를 탐구하고 자료와 근거를 활용하여 설명하거나 문제 해결에 적용할 수 있다."
    if subject in ("국어", "영어"):
        return f"{topic}에 필요한 의사소통 방법을 이해하고 듣기·말하기·읽기·쓰기 활동에 알맞게 적용할 수 있다."
    if subject in ("체육", "음악", "미술", "즐거운 생활"):
        return f"{topic}의 기본 원리와 표현 방법을 익혀 안전하고 창의적으로 참여하고 자신의 경험과 느낌을 표현할 수 있다."
    if subject in ("바른 생활", "도덕"):
        return f"{topic}의 의미와 필요성을 이해하고 자신의 생활을 성찰하여 공동체 생활에서 실천할 수 있다."
    return f"{topic}의 특징과 의미를 관찰·탐구하고 생활 및 학습 상황에 적용하여 표현할 수 있다."


def national_packs() -> list[dict]:
    out = []
    for grade, subjects in THEMES.items():
        for subject, entries in subjects.items():
            lessons = []
            for seq, entry in enumerate(entries, 1):
                domain, topic = entry.split("|", 1)
                objective = _objective(subject, topic)
                lessons.append({
                    "semester": None,
                    "seq": seq,
                    "domain": domain,
                    "unit": f"{domain} · {topic}",
                    "objective": objective,
                    "content": f"{topic}: 개념 이해 → 탐구·연습 → 문제 해결·표현 → 적용·성찰",
                    "standard": f"2022 개정 교육과정 {grade}학년 적용 내용체계·성취기준 요약: {objective}",
                    "page": "",
                })
            out.append({
                "grade": grade,
                "subject": subject,
                "publisher": "국가수준 기본안",
                "curriculum": "2022 개정",
                "source": "국가수준 교육과정 내용체계 기반 요약·재구성",
                "note": "출판사 독립형 기본 지도내용입니다. 실제 연간시간표 차시에 자동 확장되며, 교사는 채택 교과서·학교교육과정에 맞게 단원·목표·내용을 수정해 사용합니다.",
                "adaptive": True,
                "lessons": lessons,
            })
    return out
